/**
 * Article Formatter Module
 * Browser-based direct OOXML DOCX-to-Joomla article converter for College Music Symposium.
 * Faithfully ports symposium_docx_to_html.py into TypeScript using JSZip and DOMParser.
 */

import JSZip from 'jszip';

const W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main";
const R_NS = "http://schemas.openxmlformats.org/officeDocument/2006/relationships";
const REL_NS = "http://schemas.openxmlformats.org/package/2006/relationships";

const REFERENCE_HEADINGS = new Set([
  "references",
  "works cited",
  "work cited",
  "bibliography",
  "selected bibliography",
  "sources cited",
]);

const APA_YEAR_RE = /\((?:\d{4}[a-z]?(?:[–/-]\d{2,4})?(?:,\s*[A-Za-z0-9 .–/-]+)?|n\.d\.|in press|forthcoming|ca\.\s*\d{4})\)/i;
const CHICAGO_AUTHOR_DATE_RE = /^([\s\S]{2,400}?)\.\s+((?:1[5-9]\d{2}|20\d{2})[a-z]?|n\.d\.|forthcoming|in press)\.\s+([\s\S]+)$/i;
const BIB_YEAR_RE = /\b(?:1[5-9]\d{2}|20\d{2}|n\.d\.)\b/i;
const TAG_RE = /<[^>]+>/g;
const BARE_URL_RE = /https?:\/\/(?:(?!https?:\/\/|doi:\s*10\.)[^\s<>"'])+/gi;
const BARE_DOI_PREFIX_RE = /\bdoi:\s*(10\.\d{4,9}\/(?:(?!https?:\/\/|doi:\s*10\.)[^\s<>"'])+)/gi;
const HTML_TAG_OR_ANCHOR_RE = /<span class="doi">[\s\S]*?<\/span>|<a\b[^>]*>[\s\S]*?<\/a>|<[^>]+>/gi;

function htmlText(value: string): string {
  const escaped = value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/\u00a0/g, "&nbsp;");
  return escaped.replace(/ {2,}/g, (match) => "&nbsp;".repeat(match.length - 1) + " ");
}

function htmlAttr(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function truthyOnOff(value: string | null): boolean {
  if (value === null) return true;
  return !["0", "false", "False", "off", "none"].includes(value);
}

function propExplicit(rPr: Element | null, name: string): boolean | undefined {
  if (!rPr) return undefined;
  for (let i = 0; i < rPr.childNodes.length; i++) {
    const node = rPr.childNodes[i] as Element;
    if (node.nodeType !== Node.ELEMENT_NODE) continue;
    const localName = node.localName || node.nodeName.split(":").pop();
    if (localName === name) {
      const val = node.getAttributeNS(W_NS, "val") ?? node.getAttribute("w:val") ?? node.getAttribute("val");
      return truthyOnOff(val);
    }
  }
  return undefined;
}

function propEnabled(rPr: Element | null, name: string, defaultValue: boolean = false): boolean {
  const explicit = propExplicit(rPr, name);
  return explicit !== undefined ? explicit : defaultValue;
}

function vertAlign(rPr: Element | null): string | null {
  if (!rPr) return null;
  const nodes = rPr.getElementsByTagNameNS(W_NS, "vertAlign");
  if (nodes.length === 0) return null;
  return nodes[0].getAttributeNS(W_NS, "val") || nodes[0].getAttribute("w:val");
}

function directText(element: Element): string {
  const parts: string[] = [];
  const walk = (node: Node) => {
    if (node.nodeType === Node.ELEMENT_NODE) {
      const el = node as Element;
      const localName = el.localName || el.nodeName.split(":").pop();
      if (localName === "t") {
        parts.push(el.textContent || "");
      } else if (localName === "tab") {
        parts.push("\t");
      } else if (localName === "br" || localName === "cr") {
        parts.push("\n");
      } else if (localName === "instrText") {
        // Ignore Word field instruction text
      } else {
        for (let i = 0; i < el.childNodes.length; i++) {
          walk(el.childNodes[i]);
        }
      }
    }
  };
  walk(element);
  return parts.join("");
}

function paragraphText(paragraph: Element): string {
  return directText(paragraph).trim();
}

function cleanInline(value: string): string {
  return value.replace(/^(?:\s|&nbsp;)+/, "").replace(/(?:\s|&nbsp;)+$/, "");
}

export function mergeAdjacentInlineTags(value: string, mergeAcrossSpaces: boolean = false): string {
  let val = value;

  // Merge adjacent <a> tags with the exact same href (Word often splits a single URL across runs)
  let prev = "";
  while (val !== prev) {
    prev = val;
    val = val.replace(/<a\s+href="([^"]+)">([\s\S]*?)<\/a>(\s*)<a\s+href="\1">([\s\S]*?)<\/a>/gi, "<a href=\"$1\">$2$3$4</a>");
  }

  // Merge immediately adjacent inline formatting runs generated by split OOXML <w:r> elements
  val = val.replace(/<\/em><em>/gi, "");
  val = val.replace(/<\/strong><strong>/gi, "");

  if (mergeAcrossSpaces) {
    // Move leading/trailing spaces outside <em> and <strong> so adjacent italicized words join cleanly
    val = val.replace(/<em>(\s+)([\s\S]*?)<\/em>/gi, (_m, sp, inner) => (inner.trim() ? `${sp}<em>${inner}</em>` : sp));
    val = val.replace(/<em>([\s\S]*?)(\s+)<\/em>/gi, (_m, inner, sp) => (inner.trim() ? `<em>${inner}</em>${sp}` : sp));
    val = val.replace(/<\/em>(\s+)<em>/gi, "$1");
    val = val.replace(/<\/strong>(\s+)<strong>/gi, "$1");

    // Fix accidental italicization of the period + space right before a journal/book title
    val = val.replace(/([^\s<>])<em>([.?!])\s+/gi, "$1$2 <em>");
  }

  return val;
}

function normalizeHtmlSpacing(value: string): string {
  let val = value.replace(/(?:&nbsp;|\s)+/g, " ");
  val = val.replace(/\s+([,.;:)])/g, "$1");
  val = val.replace(/([(])\s+/g, "$1");
  return val.trim();
}

function htmlToPlain(value: string): string {
  const noBr = value.replace(/<br\s*\/?>/gi, " ");
  const stripped = noBr.replace(TAG_RE, "");
  return stripped
    .replace(/&nbsp;/g, " ")
    .replace(/&#8209;/g, "-")
    .replace(/&shy;/g, "")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .trim();
}

function stripTerminalPeriod(value: string): string {
  let val = value.trim();
  val = val.replace(/\.+\s*(<\/em>\s*)$/i, "$1");
  return val.replace(/\.+$/, "").trimEnd();
}

function endsWithTerminalPunct(value: string): boolean {
  const plain = htmlToPlain(value).trim();
  return /[.?!][”"’')\]]*$/.test(plain);
}

function referenceHeadingKey(value: string): string {
  const plain = htmlToPlain(value).toLowerCase().replace(/\s+/g, " ");
  return plain.replace(/^[ .:\t\r\n]+|[ .:\t\r\n]+$/g, "");
}

export function isReferenceHeading(value: string): boolean {
  return REFERENCE_HEADINGS.has(referenceHeadingKey(value));
}

function trimUrlTrailingPunct(rawUrl: string): [string, string] {
  let url = rawUrl;
  let trailing = "";

  while (url.length > 0) {
    const last = url[url.length - 1];
    if (".,;:]”’\"'".includes(last)) {
      trailing = last + trailing;
      url = url.slice(0, -1);
      continue;
    }
    if (last === ")") {
      const opens = (url.match(/\(/g) || []).length;
      const closes = (url.match(/\)/g) || []).length;
      if (closes > opens) {
        trailing = last + trailing;
        url = url.slice(0, -1);
        continue;
      }
    }
    break;
  }

  return [url, trailing];
}

function cleanDoiIdentifier(raw: string): string | null {
  const [trimmed] = trimUrlTrailingPunct(raw.trim());
  const cleaned = trimmed
    .replace(/^https?:\/\/(?:dx\.)?doi\.org\//i, "")
    .replace(/^doi:\s*/i, "")
    .replace(/[ .]+$/, "");
  if (/^10\.\d{4,9}\/\S+$/i.test(cleaned)) {
    return cleaned;
  }
  return null;
}

function doiShortText(url: string, label: string = ""): string | null {
  for (const candidate of [url, htmlToPlain(label)]) {
    if (!candidate) continue;
    const urlMatch = candidate.match(/https?:\/\/(?:dx\.)?doi\.org\/((?:(?!https?:\/\/|doi:\s*10\.)[^\s<>"'])+)/i);
    if (urlMatch) {
      const cleaned = cleanDoiIdentifier(urlMatch[1]);
      if (cleaned) return cleaned;
    }
    const prefixMatch = candidate.match(/\bdoi:\s*(10\.\d{4,9}\/(?:(?!https?:\/\/|doi:\s*10\.)[^\s<>"'])+)/i);
    if (prefixMatch) {
      const cleaned = cleanDoiIdentifier(prefixMatch[1]);
      if (cleaned) return cleaned;
    }
    const bareMatch = candidate.trim().match(/^(10\.\d{4,9}\/(?:(?!https?:\/\/|doi:\s*10\.)[^\s<>"'])+)$/i);
    if (bareMatch) {
      const cleaned = cleanDoiIdentifier(bareMatch[1]);
      if (cleaned) return cleaned;
    }
  }
  return null;
}

function renderDoiSpan(shortDoi: string): string {
  const clean = shortDoi.replace(/[ .]+$/, "");
  const href = `https://doi.org/${clean}`;
  return `<span class="doi"><a href="${htmlAttr(href)}" target="_blank" rel="noopener noreferrer">${htmlText(clean)}</a></span>`;
}

function isUrlOrDoiLabel(labelPlain: string): boolean {
  const t = labelPlain.trim();
  if (!t) return false;
  return (
    /^(?:https?:\/\/|www\.|doi:\s*|10\.\d{4,9}\/)/i.test(t) ||
    /^(?:crossref|doi|link)$/i.test(t) ||
    doiShortText("", t) !== null
  );
}

/**
 * Normalizes all hyperlinks, split DOI runs, bare DOI strings, and bare URLs inside a single citation.
 * Ensures:
 * - Split Word hyperlinks with identical href are merged into one link
 * - Partially hyperlinked DOIs absorb their plain-text prefix/suffix instead of duplicating
 * - Glued DOIs/URLs are cleanly separated and deduplicated
 * - Hyperlinked prose (such as a hyperlinked journal or article title) keeps its text/italics in place
 */
function normalizeCitationLinks(citationHtml: string): string {
  // Make idempotent if called on HTML that already contains <span class="doi">
  let val = citationHtml.replace(/<span class="doi">([\s\S]*?)<\/span>/gi, "$1");
  val = mergeAdjacentInlineTags(val, true);

  // Strip plain-text "doi:" or "https://doi.org/" immediately preceding a DOI <a> tag
  val = val.replace(
    /(?:https?:\/\/(?:dx\.)?doi\.org\/|(?:\bdoi\s*:\s*))(<a\b[^>]*href="[^"]*(?:doi\.org\/|10\.\d{4,9}\/)[^"]*"[^>]*>)/gi,
    "$1"
  );

  // Absorb unlinked DOI suffix characters right after </a> (either already in href or truncated by Word)
  val = val.replace(
    /<a\b([^>]*)href="([^"]+)"([^>]*)>([\s\S]*?)<\/a>([A-Za-z0-9._;()/:+-]+)/gi,
    (fullMatch, pre, href, post, label, tailRaw) => {
      const hrefDoi = doiShortText(href);
      if (!hrefDoi) return fullMatch;

      const labelPlain = htmlToPlain(label).trim();
      const labelAfterPrefix = labelPlain.replace(/^https?:\/\/(?:dx\.)?doi\.org\//i, "").replace(/^doi:\s*/i, "");

      // Case A: href already contains the full DOI, and plain text after </a> repeats the unlinked remainder
      if (hrefDoi.length > labelAfterPrefix.length && hrefDoi.startsWith(labelAfterPrefix)) {
        const expectedTail = hrefDoi.slice(labelAfterPrefix.length);
        if (tailRaw.startsWith(expectedTail)) {
          const leftover = tailRaw.slice(expectedTail.length);
          return `<a${pre}href="https://doi.org/${htmlAttr(hrefDoi)}"${post}>${htmlText(hrefDoi)}</a>${leftover}`;
        }
      }

      // Case B: Word auto-link truncated both href and label mid-DOI
      if (labelAfterPrefix === hrefDoi) {
        const [cleanTail, trailingPunct] = trimUrlTrailingPunct(tailRaw);
        if (cleanTail) {
          const combined = `${hrefDoi}${cleanTail}`;
          return `<a${pre}href="https://doi.org/${htmlAttr(combined)}"${post}>${htmlText(combined)}</a>${trailingPunct}`;
        }
      }

      return fullMatch;
    }
  );

  const deferredDois: string[] = [];

  // Convert <a> elements: keep prose-wrapped links (e.g., hyperlinked journal titles) in place!
  val = val.replace(/<a\b[^>]*href="([^"]+)"[^>]*>([\s\S]*?)<\/a>/gi, (_match, rawHref, label) => {
    const href = rawHref.replace(/&amp;/g, "&").trim();
    const labelPlain = htmlToPlain(label).trim();
    if (!labelPlain) return "";

    const shortDoi = doiShortText(href, isUrlOrDoiLabel(labelPlain) ? labelPlain : "");
    if (shortDoi) {
      if (isUrlOrDoiLabel(labelPlain)) {
        return renderDoiSpan(shortDoi);
      }
      // Prose text (like a journal or article title) was hyperlinked to a DOI: keep text/italics in place!
      deferredDois.push(shortDoi);
      return label;
    }

    if (/^https?:\/\//i.test(labelPlain) || /^www\./i.test(labelPlain)) {
      const [cleanHref] = trimUrlTrailingPunct(href);
      const [cleanLabel, trailing] = trimUrlTrailingPunct(labelPlain);
      return `<a href="${htmlAttr(cleanHref)}" target="_blank" rel="noopener noreferrer">${htmlText(cleanLabel)}</a>${trailing}`;
    }

    // Keep external link if part of "Retrieved from" / "Available at" or short link label; otherwise unwrap prose
    if (/^https?:\/\//i.test(href) && labelPlain.length <= 40 && !/<em>/i.test(label)) {
      return `<a href="${htmlAttr(href)}" target="_blank" rel="noopener noreferrer">${label}</a>`;
    }
    return label;
  });

  // Linkify bare URLs and bare "doi: 10.xxxx/..." outside existing HTML tags/links
  const linkifyPlainSegment = (segment: string): string => {
    let seg = segment.replace(BARE_URL_RE, (match) => {
      const [url, trailing] = trimUrlTrailingPunct(match);
      const shortDoi = doiShortText(url);
      if (shortDoi) {
        return `${renderDoiSpan(shortDoi)}${trailing}`;
      }
      return `<a href="${htmlAttr(url)}" target="_blank" rel="noopener noreferrer">${htmlText(url)}</a>${trailing}`;
    });

    seg = seg.replace(BARE_DOI_PREFIX_RE, (_match, rawDoi) => {
      const [cleanDoi, trailing] = trimUrlTrailingPunct(rawDoi);
      const shortDoi = cleanDoiIdentifier(cleanDoi);
      if (shortDoi) {
        return `${renderDoiSpan(shortDoi)}${trailing}`;
      }
      return _match;
    });

    return seg;
  };

  const parts = val.split(HTML_TAG_OR_ANCHOR_RE);
  const matches = val.match(HTML_TAG_OR_ANCHOR_RE) || [];
  const rebuilt: string[] = [];
  for (let i = 0; i < parts.length; i++) {
    rebuilt.push(linkifyPlainSegment(parts[i]));
    if (i < matches.length) {
      rebuilt.push(matches[i]);
    }
  }
  val = rebuilt.join("");

  // Append any DOI recovered from prose hyperlinks if not already present
  for (const d of deferredDois) {
    if (!val.toLowerCase().includes(d.toLowerCase())) {
      val = `${val.trimEnd()} ${renderDoiSpan(d)}`;
    }
  }

  // Ensure adjacent DOI spans are separated by a space and deduplicate identical DOIs within one citation
  val = val.replace(/<\/span>\s*<span class="doi">/gi, '</span> <span class="doi">');
  const seenDois = new Set<string>();
  val = val.replace(/<span class="doi"><a\b[^>]*>([\s\S]*?)<\/a><\/span>/gi, (full, innerDoi) => {
    const key = htmlToPlain(innerDoi).toLowerCase();
    if (seenDois.has(key)) return "";
    seenDois.add(key);
    return full;
  });

  return normalizeHtmlSpacing(val);
}

function extractTrailingLinks(value: string): [string, string[]] {
  let working = value.trim();
  const links: string[] = [];

  // Pull trailing DOI spans or URL anchors from the end of the source string
  const trailingLinkRe = /\s*(?:[.,;]\s*)?(<span class="doi">[\s\S]*?<\/span>|<a\b[^>]*>[\s\S]*?<\/a>)\.?\s*$/i;
  while (true) {
    const match = working.match(trailingLinkRe);
    if (!match || match.index === undefined) break;

    const before = working.slice(0, match.index).trimEnd();
    // Keep "Retrieved from <a ...>" or "Available at <a ...>" intact when it's a non-DOI URL
    if (!match[1].startsWith('<span class="doi">') && /\b(?:from|at)\s*$/i.test(htmlToPlain(before))) {
      break;
    }

    links.unshift(match[1]);
    working = before;
  }

  return [normalizeHtmlSpacing(working), links];
}

interface ParsedJournalParts {
  journalHtml: string;
  volume: string;
  issue: string;
  pagesHtml: string;
  italicVolume: boolean;
}

function isLikelyPublisherOrThesis(plainJournalCandidate: string): boolean {
  const lower = plainJournalCandidate.toLowerCase().trim();
  if (!lower) return true;
  if (
    /^(?:in\s+|retrieved\s+|available\s+|accessed\s+|unpublished\s+|paper\s+presented|doctoral\s+dissertation|master['’]s\s+thesis|phd\s+diss)/.test(
      lower
    )
  ) {
    return true;
  }
  if (/^[a-z .,'-]+:\s+/i.test(plainJournalCandidate) && /\b(?:press|publishers?|publishing|books|schirmer|norton|routledge|oxford|cambridge)\b/i.test(lower)) {
    return true;
  }
  return false;
}

/**
 * Separates a journal title that has no space before its volume number (e.g.,
 * `<em>Journal of Music Theory Pedagogy</em>18: 23–51` or `Journal of Music Theory Pedagogy18: 23–51`).
 */
function separateGluedJournalVolume(sourceHtml: string): string {
  // 1. Closing </em> glued directly to a digit, vol., no., or parenthesized issue/year
  let val = sourceHtml.replace(/<\/em>(?=(?:\d|vol\.\b|no\.\b|\())/gi, "</em> ");

  // 2. Plain text word (>= 3 letters ending in lowercase) glued directly to volume + issue/colon/pages
  const parts = val.split(/(<[^>]+>)/g);
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i];
    if (!part || part.startsWith("<") || /(?:https?:\/\/|doi:)/i.test(part)) continue;
    parts[i] = part.replace(
      /([A-Za-z]{2,}[a-z])(\d{1,4}[A-Za-z]?)(?=\s*(?:\([^)]+\))?\s*(?::\s*[A-Za-z]?\d|,\s*(?:no\.\b|pp?\.\b|\d+\s*[–-]\s*\d+))|\s*,\s*no\.\s*\d)/g,
      "$1 $2"
    );
  }
  return parts.join("");
}

/**
 * Attempts to parse an APA / hybrid periodical source clause into journal, volume, issue, and pages.
 * Handles both italicized and unitalicized journal titles, optional issue numbers, and online-only
 * journals without page numbers (e.g., College Music Symposium, 62(1)).
 */
function parseApaJournalParts(sourceWithoutLinks: string): ParsedJournalParts | null {
  const separated = separateGluedJournalVolume(sourceWithoutLinks);
  const trimmed = separated.trim().replace(/\.+$/, "").trim();
  if (!trimmed) return null;

  const hasLeadingEm = /^<em>/i.test(trimmed);
  const plain = htmlToPlain(trimmed).replace(/\.+$/, "").trim();
  if (!plain || isLikelyPublisherOrThesis(plain)) return null;

  // Pattern 1: Journal, [vol.] 45[(2)], [pp.] 112–128  OR  Journal 45(2), 112–128 / Journal 45(2): 112–128
  const withPages = plain.match(
    /^(.+?)(?:,\s*(?:vol\.\s*)?|\s+)(\d{1,4}[A-Za-z]?(?:[–-]\d{1,4})?)\s*(?:,\s*no\.\s*([0-9A-Za-z–/-]+)|(\([^)]+\)))?\s*(?:,|:)\s*(?:pp?\.\s*)?([A-Za-z0-9–\-.,; ()]+)$/i
  );
  if (withPages) {
    const journal = withPages[1].trim().replace(/,+$/, "").trim();
    const volume = withPages[2].trim();
    const issueRaw = (withPages[3] ? `(${withPages[3].trim()})` : withPages[4] || "").trim();
    const pages = withPages[5].trim().replace(/^[ ,.]+|[ ,.]+$/g, "");

    // Guard against matching "Publisher, 2020" if there is no issue and "volume" is a 4-digit year without page range
    const volIsYear = /^(?:1[89]\d{2}|20\d{2})$/.test(volume);
    const pagesLookValid = /^(?:[A-Za-z]?\d+|\d+\s*[–-]\s*\d+|article\s+\w+|e\d+)/i.test(pages);
    if (!isLikelyPublisherOrThesis(journal) && pagesLookValid && (!volIsYear || issueRaw || /\d+\s*[–-]\s*\d+/.test(pages))) {
      return {
        journalHtml: htmlText(journal),
        volume,
        issue: issueRaw,
        pagesHtml: htmlText(pages),
        italicVolume: true,
      };
    }
  }

  // Pattern 2: Online journal with volume + issue and NO page numbers (e.g., "College Music Symposium, 62(1)")
  const volIssueOnly = plain.match(
    /^(.+?)(?:,\s*(?:vol\.\s*)?|\s+)(\d{1,4}[A-Za-z]?)\s*(?:,\s*no\.\s*([0-9A-Za-z–/-]+)|(\([^)]+\)))$/i
  );
  if (volIssueOnly) {
    const journal = volIssueOnly[1].trim().replace(/,+$/, "").trim();
    const volume = volIssueOnly[2].trim();
    const issueRaw = (volIssueOnly[3] ? `(${volIssueOnly[3].trim()})` : volIssueOnly[4] || "").trim();
    if (!isLikelyPublisherOrThesis(journal) && issueRaw && !BIB_YEAR_RE.test(issueRaw)) {
      return {
        journalHtml: htmlText(journal),
        volume,
        issue: issueRaw,
        pagesHtml: "",
        italicVolume: true,
      };
    }
  }

  // Pattern 3: Leading <em> journal with volume only and no pages (e.g., "<em>College Music Symposium</em>, 62")
  if (hasLeadingEm) {
    const volOnly = plain.match(/^(.+?)(?:,\s*|\s+)(\d{1,3}[A-Za-z]?)$/);
    if (volOnly && !isLikelyPublisherOrThesis(volOnly[1])) {
      return {
        journalHtml: htmlText(volOnly[1].trim().replace(/,+$/, "")),
        volume: volOnly[2].trim(),
        issue: "",
        pagesHtml: "",
        italicVolume: true,
      };
    }
  }

  return null;
}

function formatReferenceSource(sourceHtml: string): string {
  const [withoutLinks, links] = extractTrailingLinks(sourceHtml);

  // Separate any trailing "Retrieved ... from ..." clause so the preceding journal part still formats cleanly
  let mainSource = separateGluedJournalVolume(withoutLinks);
  let retrievalTail = "";
  const retrievalMatch = mainSource.match(/^(.*?\S)\s*\.\s*((?:Retrieved|Accessed|Available)\b[\s\S]*)$/i);
  if (retrievalMatch) {
    mainSource = retrievalMatch[1].trim();
    retrievalTail = ensureTerminalPeriod(retrievalMatch[2].trim());
  }

  const plain = htmlToPlain(mainSource);
  const lowerPlain = plain.toLowerCase();

  const isBookChapterOrRetrievalOnly =
    lowerPlain.startsWith("in ") ||
    lowerPlain.startsWith("retrieved ") ||
    lowerPlain.startsWith("available ") ||
    lowerPlain.startsWith("accessed ");

  let rendered = mainSource;

  if (!isBookChapterOrRetrievalOnly) {
    const parsed = parseApaJournalParts(mainSource);
    if (parsed) {
      let r = `<span class="journal"><em>${parsed.journalHtml}</em></span>`;
      if (parsed.volume) {
        const volInner = parsed.italicVolume ? `<em>${htmlText(parsed.volume)}</em>` : htmlText(parsed.volume);
        r += `, <span class="volume">${volInner}</span>`;
      }
      if (parsed.issue) {
        // NEVER insert a space between volume and parenthesized issue number: e.g., 45(2)
        r += parsed.volume
          ? `<span class="issue">${htmlText(parsed.issue)}</span>`
          : `, <span class="issue">${htmlText(parsed.issue)}</span>`;
      }
      if (parsed.pagesHtml) {
        r += `, <span class="pages">${parsed.pagesHtml}</span>`;
      }
      rendered = `${r}.`;
    } else if (/^<em>[\s\S]+<\/em>\.?$/i.test(mainSource.trim()) && (mainSource.match(/<em>/gi) || []).length === 1) {
      // Pure italicized journal name (e.g., online journal without volume/pages)
      rendered = `<span class="journal"><em>${htmlText(plain.replace(/[,.\s]+$/, ""))}</em></span>.`;
    } else if (/^<em>/i.test(mainSource.trim())) {
      // Leading <em> followed by Chicago-style issue/date or status text (e.g., ". Advance online publication")
      rendered = ensureTerminalPeriod(spanBibliographyJournalSource(mainSource.trim(), true));
    } else {
      rendered = ensureTerminalPeriod(mainSource);
    }
  } else {
    rendered = ensureTerminalPeriod(mainSource);
  }

  if (retrievalTail) {
    rendered = `${rendered} ${retrievalTail}`;
  }
  if (links.length > 0) {
    rendered = `${rendered} ${links.join(" ")}`;
  }

  return normalizeHtmlSpacing(rendered);
}

function splitReferenceYear(value: string): [string, string, string] | null {
  const match = APA_YEAR_RE.exec(value);
  if (!match) return null;

  let periodEnd = match.index + match[0].length;
  if (periodEnd < value.length && value[periodEnd] === ".") {
    periodEnd += 1;
  }

  return [
    value.slice(0, match.index).trim(),
    match[0],
    value.slice(periodEnd).trim(),
  ];
}

function isApaYearSplit(split: [string, string, string]): boolean {
  const [beforeYear, , remainder] = split;
  const plain = htmlToPlain(beforeYear).trim();
  if (!plain || plain.length > 800) return false;
  if (/[“"‘]|<em>|<\/em>/i.test(beforeYear)) return false;
  // Exclude Chicago journal citations like "Author. Title. Journal 64, no. 2 (2020): 145–180"
  if (/^:/.test(remainder.trim())) return false;
  if (/\b\d{1,4}(?:\s*,\s*no\.\s*[\w–-]+)?\s*$/i.test(plain)) return false;
  return true;
}

function consumeLeadingEmSequence(value: string): [string, string] {
  const titleParts: string[] = [];
  let remaining = value.trimStart();

  while (true) {
    const match = remaining.match(/^(<em>[\s\S]*?<\/em>)/i);
    if (!match) break;

    titleParts.push(match[1]);
    remaining = remaining.slice(match[0].length);
    const spaceMatch = remaining.match(/^\s+/);
    const sep = spaceMatch ? " " : "";
    remaining = remaining.trimStart();
    if (!remaining.toLowerCase().startsWith("<em>")) break;
    if (sep) titleParts.push(" ");
  }

  return [normalizeHtmlSpacing(titleParts.join("")), remaining.trim()];
}

const TITLE_ABBREV_WORDS = new Set([
  "jr", "sr", "ed", "eds", "vol", "vols", "no", "nos", "op", "bwv", "hob",
  "ca", "vs", "etc", "al", "p", "pp", "trans", "rev", "comp", "dr", "mr", "mrs", "ms", "st", "fig", "no"
]);

/**
 * Finds sentence boundaries (`. `, `? `, `! `) outside HTML tags and outside parentheses/brackets.
 */
function findTopLevelSentenceSplits(html: string): Array<{ titlePart: string; restPart: string }> {
  const results: Array<{ titlePart: string; restPart: string }> = [];
  let inTag = false;
  let parenDepth = 0;
  let bracketDepth = 0;

  for (let i = 0; i < html.length; i++) {
    const ch = html[i];
    if (ch === "<") {
      inTag = true;
      continue;
    }
    if (ch === ">") {
      inTag = false;
      continue;
    }
    if (inTag) continue;

    if (ch === "(") parenDepth++;
    else if (ch === ")" && parenDepth > 0) parenDepth--;
    else if (ch === "[") bracketDepth++;
    else if (ch === "]" && bracketDepth > 0) bracketDepth--;

    if (parenDepth === 0 && bracketDepth === 0 && (ch === "." || ch === "?" || ch === "!")) {
      // Advance past optional closing </em> or closing quote right after punctuation
      let endIdx = i + 1;
      while (true) {
        const sub = html.slice(endIdx);
        const closeEm = sub.match(/^<\/em>/i);
        if (closeEm) {
          endIdx += closeEm[0].length;
          continue;
        }
        if (/^[”"’']/.test(sub)) {
          endIdx += 1;
          continue;
        }
        break;
      }

      const afterSlice = html.slice(endIdx);
      const wsMatch = afterSlice.match(/^\s+/);
      if (!wsMatch) continue;

      const restPart = afterSlice.slice(wsMatch[0].length).trim();
      if (!restPart) continue;

      // Check word right before `.` to avoid splitting on initials ("J. S. Bach") or "Op. 12"
      if (ch === ".") {
        const beforePlain = htmlToPlain(html.slice(0, i)).trim();
        const lastToken = (beforePlain.split(/\s+/).pop() || "").replace(/^[^A-Za-z]+|[^A-Za-z.]+$/g, "");
        const lastLower = lastToken.toLowerCase().replace(/\./g, "");
        const restStartsWithSource = /^<em>/i.test(restPart) || /^In\b/.test(restPart);

        if (!restStartsWithSource) {
          if (lastToken.length === 1 && /^[A-Z]$/.test(lastToken)) continue;
          if (TITLE_ABBREV_WORDS.has(lastLower)) continue;
          if (/^(?:[A-Z]\.){1,3}[A-Z]$/.test(lastToken)) continue; // e.g., U.S.
        }
      }

      results.push({
        titlePart: html.slice(0, endIdx).trim(),
        restPart,
      });
    }
  }

  return results;
}

/**
 * Splits everything after `(Year).` in an APA citation into `[titleHtml, sourceHtml]`.
 * Preserves inline `<em>` inside article titles (e.g. musical work titles or foreign terms)
 * while still accurately isolating journal titles (italicized or unitalicized), book chapters, and publishers.
 */
function splitApaTitleAndSource(cleanedRem: string): [string, string] {
  const [withoutTrailingLinks, trailingLinks] = extractTrailingLinks(cleanedRem);
  const attachLinks = (source: string): string => {
    if (trailingLinks.length === 0) return source;
    return normalizeHtmlSpacing(`${source} ${trailingLinks.join(" ")}`);
  };

  if (!withoutTrailingLinks) {
    return ["", attachLinks("")];
  }

  const splits = findTopLevelSentenceSplits(withoutTrailingLinks);

  // 1. Prefer split immediately before "In ..." (book chapter) or a journal source (italicized or plain)
  for (const sp of splits) {
    if (/^In\b/.test(sp.restPart)) {
      return [sp.titlePart, attachLinks(sp.restPart)];
    }
    if (/^<em>/i.test(sp.restPart) || parseApaJournalParts(sp.restPart) !== null) {
      return [sp.titlePart, attachLinks(sp.restPart)];
    }
  }

  // 2. Otherwise (standalone book, thesis, report, or publisher tail), split at first sentence boundary
  if (splits.length > 0) {
    return [splits[0].titlePart, attachLinks(splits[0].restPart)];
  }

  // 3. Fallback if book title in <em> had no period separating edition/publisher
  if (/^<em>/i.test(withoutTrailingLinks)) {
    const [emTitle, afterEm] = consumeLeadingEmSequence(withoutTrailingLinks);
    if (afterEm && !/^[,:;]/.test(afterEm)) {
      return [emTitle, attachLinks(afterEm)];
    }
  }

  return [withoutTrailingLinks, attachLinks("")];
}

function ensureTerminalPeriod(value: string): string {
  const trimmed = value.trim();
  if (!trimmed) return trimmed;
  const plain = htmlToPlain(trimmed);
  if (/[.?!][”"’')\]]*$/.test(plain)) return trimmed;
  return `${trimmed}.`;
}

function splitBibliographyAuthor(value: string): [string, string] {
  const trimmed = value.trim();
  const plain = htmlToPlain(trimmed);
  if (/^[“"']/.test(plain) || /^<em>/i.test(trimmed)) return ["", trimmed];

  const quoteMatch = plain.match(/\s*[,“"]\s*([“”"])/);
  if (quoteMatch && (quoteMatch.index ?? 0) <= 180) {
    const authorPlain = plain.slice(0, quoteMatch.index).replace(/^[ ,]+|[ ,]+$/g, "");
    for (let index = 0; index <= trimmed.length; index++) {
      if (htmlToPlain(trimmed.slice(0, index)).replace(/^[ ,]+|[ ,]+$/g, "") === authorPlain) {
        return [trimmed.slice(0, index).replace(/^[ ,]+|[ ,]+$/g, ""), trimmed.slice(index).replace(/^[ ,]+/, "")];
      }
    }
  }

  const dotRe = /\.(?:\s+|(?=<em>|[“”"]))|(?<=—)\.(?:\s+)/g;
  let match: RegExpExecArray | null;
  while ((match = dotRe.exec(trimmed)) !== null) {
    const rest = trimmed.slice(match.index + match[0].length).trimStart();
    const restPlain = htmlToPlain(rest);
    const nextWord = restPlain.split(" ")[0].replace(/^[ ,]+|[ ,]+$/g, "");
    const prevWords = htmlToPlain(trimmed.slice(0, match.index)).split(/\s+/);
    const prevWord = prevWords[prevWords.length - 1]?.replace(/^[ ,]+|[ ,]+$/g, "") || "";

    if (rest.startsWith("“") || rest.startsWith('"') || rest.startsWith("<em>")) {
      return [trimmed.slice(0, match.index + 1).trim(), rest.trim()];
    }
    if (["Jr.", "Sr.", "II", "III", "IV", "et"].includes(nextWord)) continue;
    if (prevWord.length === 1 && prevWord === prevWord.toUpperCase()) {
      const beforeDotPlain = htmlToPlain(trimmed.slice(0, match.index)).trim();
      // Single-author "Last, First M." ends at "M." unless followed by another initial;
      // whereas "J. S. Bach" or "Last, First, and First M. Last" continues past "M." to the surname.
      const isSingleInvertedWithMiddleInitial =
        /^[A-ZÀ-ÖØ-Þ][A-Za-zÀ-ÿ'’ -]+,\s+(?:[A-ZÀ-ÖØ-Þ][A-Za-zÀ-ÿ'’-]+(?:\s+[A-Z]\.)*\s+[A-Z]|(?:[A-Z]\.\s*)*[A-Z])$/.test(beforeDotPlain) &&
        !/^[A-Z]\./.test(restPlain);
      if (!isSingleInvertedWithMiddleInitial) continue;
    }
    if (/^[A-Z]/.test(restPlain)) {
      return [trimmed.slice(0, match.index + 1).trim(), rest.trim()];
    }
  }

  return ["", trimmed];
}

function extractQuotedTitle(value: string): [string, string, string, string] | null {
  const v = value.trimStart();
  const openQuote = v[0];
  if (openQuote !== '"' && openQuote !== "“") return null;
  const closeQuote = openQuote === "“" ? "”" : '"';
  const closeIndex = v.indexOf(closeQuote, 1);
  if (closeIndex < 0) return null;
  let title = v.slice(1, closeIndex).trim();
  let rest = v.slice(closeIndex + 1).trim();
  // If the author placed a period or comma outside the closing quote (“Title”. Journal...), normalize cleanly
  if (/^[.,]/.test(rest)) {
    const punct = rest[0];
    rest = rest.slice(1).trimStart();
    if (!/[.?!,]$/.test(htmlToPlain(title))) {
      title = `${title}${punct}`;
    }
  }
  return [openQuote, title, closeQuote, rest];
}

function extractBibliographyTitle(value: string): [string, string, boolean, string, string] {
  const quoted = extractQuotedTitle(value);
  if (quoted) {
    const [openQuote, title, closeQuote, rest] = quoted;
    return [title, rest, true, openQuote, closeQuote];
  }

  if (value.toLowerCase().startsWith("<em>")) {
    const splits = findTopLevelSentenceSplits(value);
    if (splits.length > 0) {
      return [splits[0].titlePart, splits[0].restPart, false, "", ""];
    }
    const [title, rest] = consumeLeadingEmSequence(value);
    return [title, rest.replace(/^\./, "").trim(), false, "", ""];
  }

  const splits = findTopLevelSentenceSplits(value);
  if (splits.length > 0) {
    return [splits[0].titlePart, splits[0].restPart, false, "", ""];
  }

  return [value.trim(), "", false, "", ""];
}

function spanYearsInText(value: string): string {
  // Never inject <span class="year"> inside DOI spans, <a> links, or bare URLs
  const protectedRe = /(<span class="doi">[\s\S]*?<\/span>|<a\b[^>]*>[\s\S]*?<\/a>|https?:\/\/\S+|<[^>]+>)/gi;
  const parts = value.split(protectedRe);
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i];
    if (!part || part.startsWith("<") || /^https?:\/\//i.test(part)) continue;
    parts[i] = part.replace(new RegExp(BIB_YEAR_RE.source, "gi"), (m) => `<span class="year">${m}</span>`);
  }
  return parts.join("");
}

function spanBibliographyJournalSource(value: string, afterQuotedArticleTitle: boolean = false): string {
  let val = separateGluedJournalVolume(value.trim());
  if (!val) return val;

  // If the author italicized "Journal Title, 45" or "Journal Title 45" together in one <em>, split the volume out cleanly
  val = val.replace(
    /<em>([\s\S]*?[A-Za-z.])(?:\s*,\s*|\s+)(\d{1,4}[A-Za-z]?)<\/em>(?=\s*(?:\([^)]+\)|,\s*no\.\b|;|:|\.|,\s*(?:pp?\.\s*)?\d))/i,
    (_m, jInner, vol) =>
      `<span class="journal"><em>${jInner.trim().replace(/,+$/, "").trim()}</em></span>, <span class="volume"><em>${vol}</em></span>`
  );

  // Wrap first <em>...</em> in <span class="journal"> while preserving surrounding spaces & moving any trailing comma outside </em></span>
  if (!val.includes('<span class="journal">')) {
    val = val.replace(/<em>([\s\S]*?)<\/em>/i, (_match, inner: string) => {
      const leadWs = inner.match(/^\s*/)?.[0] || "";
      const trailWs = inner.match(/\s*$/)?.[0] || "";
      let core = inner.trim();
      let hadTrailingComma = false;
      if (core.endsWith(",")) {
        core = core.slice(0, -1).trimEnd();
        hadTrailingComma = true;
      }
      if (!core) return inner;
      return `${leadWs}<span class="journal"><em>${core}</em></span>${hadTrailingComma ? "," : ""}${trailWs}`;
    });
  }

  // If an unitalicized journal citation follows the article title, detect and italicize the journal title!
  if (!val.includes('<span class="journal">')) {
    const [withoutLinks, links] = extractTrailingLinks(val);
    const plainNoLinks = separateGluedJournalVolume(htmlToPlain(withoutLinks));
    if (!isLikelyPublisherOrThesis(plainNoLinks)) {
      const chicagoUnitalicized = plainNoLinks.match(
        /^([A-Z0-9][A-Za-z0-9 &/'’‘“-]{1,120}?)(?:\s*,\s*(?:vol\.\s*)?(?=\d)|\s+(?=(?:vol\.\s*)?\d))((?:vol\.\s*)?\d{1,4}[A-Za-z]?[\s\S]*)$/i
      );
      if (chicagoUnitalicized) {
        const jName = chicagoUnitalicized[1].trim().replace(/,+$/, "").trim();
        const volAndTail = chicagoUnitalicized[2].trim();
        const looksLikeJournalTail =
          /^(?:vol\.\s*)?\d{1,4}[A-Za-z]?\s*(?:,\s*no\.\s*[0-9A-Za-z–/-]+|\([^)]+\)|\s*:\s*[A-Za-z]?\d|,\s*(?:pp?\.\s*\d|\d+\s*[–-]\s*\d+))/i.test(
            volAndTail
          );
        const isEditionOrBookVol = /^(?:vol|vols|ed|eds|trans|rev|no)\.?$/i.test(jName);
        if (looksLikeJournalTail && !isEditionOrBookVol && !isLikelyPublisherOrThesis(jName)) {
          val = `<span class="journal"><em>${htmlText(jName)}</em></span>, ${htmlText(volAndTail)}${
            links.length ? " " + links.join(" ") : ""
          }`;
        } else if (afterQuotedArticleTitle) {
          const apaUnitalicized = parseApaJournalParts(withoutLinks);
          if (apaUnitalicized) {
            return formatReferenceSource(val);
          }
        }
      } else if (afterQuotedArticleTitle) {
        const apaUnitalicized = parseApaJournalParts(withoutLinks);
        if (apaUnitalicized) {
          return formatReferenceSource(val);
        }
      }
    }
  }

  const VOL_TOKEN = `(?:<span class="volume">)?(<em>)?(\\d+[A-Za-z]?)(?:<\\/em>)?(?:<\\/span>)?`;
  const renderVol = (emTag: string | undefined, vol: string) =>
    `<span class="volume">${emTag ? `<em>${vol}</em>` : vol}</span>`;

  // 1. Chicago full: *Journal*[,] [vol.] 45, no. 2 (Spring 2020)[: 112–128]
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*(vol\\.\\s*)?${VOL_TOKEN}\\s*,\\s*no\\.\\s*([0-9A-Za-z–/-]+|\\([^)]+\\))\\s*(\\([^)]*\\))(?:\\s*:\\s*([^.<]+))?\\.?`,
      "i"
    ),
    (_m, j, volPrefix, emTag, vol, iss, date, pgs) => {
      const cleanIss = iss.replace(/^\(|\)$/g, "").trim();
      const vPrefix = volPrefix ? "vol. " : "";
      const base = `${j}, ${vPrefix}${renderVol(emTag, vol)}, no. <span class="issue">${cleanIss}</span> ${spanYearsInText(date)}`;
      return pgs ? `${base}: <span class="pages">${pgs.trim()}</span>.` : `${base}.`;
    }
  );

  // 2. Volume + no. issue + pages WITHOUT parenthesized year: *Journal*[,] 45, no. 2: 112–128
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*(vol\\.\\s*)?${VOL_TOKEN}\\s*,\\s*no\\.\\s*([0-9A-Za-z–/-]+)\\s*(:|,)\\s*(?:pp?\\.\\s*)?([^.<]+)\\.?`,
      "i"
    ),
    (_m, j, volPrefix, emTag, vol, iss, sep, pgs) => {
      const vPrefix = volPrefix ? "vol. " : "";
      return `${j}, ${vPrefix}${renderVol(emTag, vol)}, no. <span class="issue">${iss.trim()}</span>${sep} <span class="pages">${pgs.trim()}</span>.`;
    }
  );

  // 3. *Journal*[,] 45(2) (2020): 112–128 (both parenthesized issue AND parenthesized year)
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*${VOL_TOKEN}\\s*(\\((?!1[5-9]\\d{2}|20\\d{2})[^)]+\\))\\s*(\\([^)]*\\))\\s*:\\s*([^.<]+)\\.?`,
      "i"
    ),
    (_m, j, emTag, vol, iss, date, pgs) =>
      `${j}, ${renderVol(emTag, vol)}<span class="issue">${iss}</span> ${spanYearsInText(date)}: <span class="pages">${pgs.trim()}</span>.`
  );

  // 4. *Journal*[,] 45 (2020): 112–128  vs  *Journal*[,] 2(1): 11–42
  //    Always comma + space after journal; keep space before 4-digit (year), NEVER add space before parenthesized (issue)!
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*${VOL_TOKEN}\\s*(\\([^)]+\\))\\s*:\\s*([^.<]+)\\.?`,
      "i"
    ),
    (_m, j, emTag, vol, parenGroup, pgs) => {
      if (BIB_YEAR_RE.test(parenGroup)) {
        return `${j}, ${renderVol(emTag, vol)} ${spanYearsInText(parenGroup)}: <span class="pages">${pgs.trim()}</span>.`;
      }
      return `${j}, ${renderVol(emTag, vol)}<span class="issue">${parenGroup}</span>: <span class="pages">${pgs.trim()}</span>.`;
    }
  );

  // 5. *Journal*[,] 18: 23–51 (volume + colon + pages without issue or year, e.g. Journal of Music Theory Pedagogy, 18: 23–51)
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*${VOL_TOKEN}\\s*:\\s*([^.<]+)\\.?`,
      "i"
    ),
    (_m, j, emTag, vol, pgs) =>
      `${j}, ${renderVol(emTag, vol)}: <span class="pages">${pgs.trim()}</span>.`
  );

  // 6. MLA style: *Journal*[,] vol. 45, no. 2, 2020, pp. 112–128
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*vol\\.\\s*${VOL_TOKEN}\\s*,\\s*no\\.\\s*([0-9A-Za-z–/-]+)\\s*,\\s*([^,:<]+?)\\s*,\\s*(pp?\\.)\\s*([^.<]+)\\.?`,
      "i"
    ),
    (_m, j, emTag, vol, iss, date, ppLabel, pgs) =>
      `${j}, vol. ${renderVol(emTag, vol)}, no. <span class="issue">${iss}</span>, ${spanYearsInText(date.trim())}, ${ppLabel} <span class="pages">${pgs.trim()}</span>.`
  );

  // 7. Comma style in bibliography: *Journal*[,] 45(2), 112–128  or  *Journal*[,] 45(2)
  val = val.replace(
    new RegExp(
      `(<span class="journal"><em>[\\s\\S]*?<\\/em><\\/span>)\\s*,?\\s*${VOL_TOKEN}\\s*(\\((?!1[5-9]\\d{2}|20\\d{2})[^)]+\\))?(?:\\s*,\\s*(?:pp?\\.\\s*)?(\\d+\\s*[-–]\\s*\\d+|e\\d+))?\\.?`,
      "i"
    ),
    (full, j, emTag, vol, iss, pgs) => {
      if (!iss && !pgs) return full;
      let out = `${j}, ${renderVol(emTag, vol)}`;
      if (iss) out += `<span class="issue">${iss}</span>`;
      if (pgs) out += `, <span class="pages">${pgs.trim()}</span>`;
      return `${out}.`;
    }
  );

  // 8. Issue-only journal without volume: *Journal*[,] no. 65 (Spring 1998): 11–42
  val = val.replace(
    /(<span class="journal"><em>[\s\S]*?<\/em><\/span>)\s*,?\s*no\.\s*([0-9A-Za-z–/-]+)\s*(\([^)]*\))(?:\s*:\s*([^.<]+))?\.?/i,
    (_m, j, iss, date, pgs) => {
      const base = `${j}, no. <span class="issue">${iss}</span> ${spanYearsInText(date)}`;
      return pgs ? `${base}: <span class="pages">${pgs.trim()}</span>.` : `${base}.`;
    }
  );

  // 9. Journal with page range only: *Journal*[,] 112–128
  val = val.replace(
    /(<span class="journal"><em>[\s\S]*?<\/em><\/span>)\s*,?\s*(\d+\s*[-–]\s*\d+)\.?/i,
    (_m, j, pgs) => `${j}, <span class="pages">${pgs.trim()}</span>.`
  );

  // Safety net A: always ensure a comma + space after <span class="journal">...</span> before volume, issue, pages, vol., no., or digits
  val = val.replace(
    /(<span class="journal"><em>[\s\S]*?<\/em><\/span>)\s*(?=(?:<span class="(?:volume|issue|pages)">|vol\.\b|no\.\b|pp?\.\b|\d))/gi,
    "$1, "
  );

  // Safety net B: remove any stray space between volume and non-year parenthesized issue right after journal
  val = val.replace(
    /(<span class="journal">[\s\S]*?<\/span>[,]?\s*(?:<span class="volume">)?(?:<em>)?\d+[A-Za-z]?(?:<\/em>)?(?:<\/span>)?)\s+(\((?!1[5-9]\d{2}|20\d{2})[^)]+\))/gi,
    "$1$2"
  );

  return val;
}

function formatBibliographyCitation(citationHtml: string): string {
  const cleaned = normalizeCitationLinks(citationHtml);
  const [authorHtml, remainder] = splitBibliographyAuthor(cleaned);
  const [titleHtml, sourceHtml, quoted, openQuote, closeQuote] = extractBibliographyTitle(remainder);

  const parts: string[] = [];
  if (authorHtml) {
    if (quoted && !authorHtml.trimEnd().endsWith(".")) {
      parts.push(`<span class="author">${authorHtml.trim()}</span>,`);
    } else {
      parts.push(`<span class="author">${ensureTerminalPeriod(authorHtml)}</span>`);
    }
  }

  let title = normalizeHtmlSpacing(titleHtml);
  if (title) {
    if (quoted) {
      let quoteSuffix = "";
      if (title.endsWith(",")) {
        title = title.slice(0, -1).trimEnd();
        quoteSuffix = ",";
      }
      parts.push(`${openQuote}<span class="title">${title}</span>${quoteSuffix}${closeQuote}`);
    } else {
      const cleanedTitle = endsWithTerminalPunct(title) ? title : ensureTerminalPeriod(stripTerminalPeriod(title));
      parts.push(`<span class="title">${cleanedTitle}</span>`);
    }
  }

  let source = normalizeHtmlSpacing(sourceHtml);
  if (source) {
    source = spanBibliographyJournalSource(source, quoted);
    if (!source.includes('<span class="year">')) {
      source = spanYearsInText(source);
    }
    parts.push(source);
  }

  let rendered = normalizeHtmlSpacing(parts.join(" "));
  rendered = rendered.replace(/\s+([,.;:])/g, "$1");
  rendered = rendered.replace(/(<\/span>)\s*\.\s*(<\/span>)/g, "$1$2");
  rendered = rendered.replace(/(?<!\.)\.\.(?!\.)/g, ".");
  rendered = rendered.replace(/(<span class="doi">[\s\S]*?<\/span>)\.\s*$/i, "$1");
  return rendered;
}

function formatChicagoAuthorDateCitation(authorRaw: string, yearRaw: string, remainderRaw: string): string {
  const author = ensureTerminalPeriod(normalizeHtmlSpacing(authorRaw));
  const year = `<span class="year">${htmlText(yearRaw.trim())}</span>.`;
  const rem = remainderRaw.trim();

  if (/^[“"']/.test(htmlToPlain(rem))) {
    const [titleHtml, sourceHtml, quoted, openQuote, closeQuote] = extractBibliographyTitle(rem);
    const parts = [`<span class="author">${author}</span>`, year];
    if (titleHtml) {
      parts.push(
        quoted
          ? `${openQuote}<span class="title">${normalizeHtmlSpacing(titleHtml)}</span>${closeQuote}`
          : `<span class="title">${ensureTerminalPeriod(stripTerminalPeriod(normalizeHtmlSpacing(titleHtml)))}</span>`
      );
    }
    if (sourceHtml) {
      parts.push(spanBibliographyJournalSource(normalizeHtmlSpacing(sourceHtml), quoted));
    }
    let rendered = normalizeHtmlSpacing(parts.join(" "));
    rendered = rendered.replace(/(?<!\.)\.\.(?!\.)/g, ".");
    rendered = rendered.replace(/(<span class="doi">[\s\S]*?<\/span>)\.\s*$/i, "$1");
    return rendered;
  }

  const [rawTitle, rawSource] = splitApaTitleAndSource(rem);
  const parts = [`<span class="author">${author}</span>`, year];
  if (rawTitle) {
    const titleNorm = normalizeHtmlSpacing(rawTitle);
    if (endsWithTerminalPunct(titleNorm) && /[?!][”"’')\]*]*$/.test(htmlToPlain(titleNorm))) {
      parts.push(`<span class="title">${titleNorm}</span>`);
    } else {
      parts.push(`<span class="title">${stripTerminalPeriod(titleNorm)}</span>.`);
    }
  }
  if (rawSource) {
    // Handle Chicago colon-style journal source (e.g., *Journal* 64(2): 145–180) or APA comma-style
    if (/:\s*\d/.test(htmlToPlain(rawSource)) && !parseApaJournalParts(extractTrailingLinks(rawSource)[0])) {
      parts.push(spanBibliographyJournalSource(normalizeHtmlSpacing(rawSource), true));
    } else {
      parts.push(formatReferenceSource(rawSource));
    }
  }
  let rendered = normalizeHtmlSpacing(parts.join(" "));
  rendered = rendered.replace(/(?<!\.)\.\.(?!\.)/g, ".");
  rendered = rendered.replace(/(<span class="doi">[\s\S]*?<\/span>)\.\s*$/i, "$1");
  return rendered;
}

export function formatReferenceCitation(citationHtml: string): string {
  const strippedLeadingNumber = citationHtml.trim().replace(/^(?:\[\d+\]|\d+\.)\s+/, "");
  const norm = normalizeCitationLinks(strippedLeadingNumber);
  const split = splitReferenceYear(norm);

  if (!split || !isApaYearSplit(split)) {
    // Check Chicago Author-Date ("Smith, Jane. 2020. ...")
    const cadMatch = norm.match(CHICAGO_AUTHOR_DATE_RE);
    if (cadMatch && !/[“"‘]|<em>|<\/em>/i.test(cadMatch[1])) {
      return formatChicagoAuthorDateCitation(cadMatch[1], cadMatch[2], cadMatch[3]);
    }
    return formatBibliographyCitation(norm);
  }

  const [authorHtml, year, remainder] = split;
  const cleanedRem = cleanInline(remainder);
  const [rawTitleHtml, rawSourceHtml] = splitApaTitleAndSource(cleanedRem);

  const titleNorm = normalizeHtmlSpacing(rawTitleHtml);
  const sourceHtml = normalizeHtmlSpacing(rawSourceHtml);

  const parts = [
    `<span class="author">${normalizeHtmlSpacing(authorHtml)}</span>`,
    `<span class="year">${htmlText(year)}</span>.`,
  ];

  if (titleNorm) {
    const plainTitle = htmlToPlain(titleNorm);
    if (/[?!][”"’')\]]*$/.test(plainTitle)) {
      parts.push(`<span class="title">${titleNorm}</span>`);
    } else {
      parts.push(`<span class="title">${stripTerminalPeriod(titleNorm)}</span>.`);
    }
  }

  if (sourceHtml) {
    parts.push(formatReferenceSource(sourceHtml));
  }

  let rendered = normalizeHtmlSpacing(parts.join(" "));
  rendered = rendered.replace(/(<\/(?:span|em)>)\s*\.\./g, "$1.");
  rendered = rendered.replace(/from(?:&nbsp;|\s)*\.\s*(<a\b)/gi, "from $1");
  rendered = rendered.replace(/(?<!\.)\.\.(?!\.)/g, ".");
  return rendered;
}

