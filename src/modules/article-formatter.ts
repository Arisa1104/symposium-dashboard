const CITY_STATE_PUBLISHER_RE =
  /^[A-Z][A-Za-z .'-]+,\s*(?:[A-Z]{2}|UK|U\.K\.|U\.S\.A?\.|Canada|England|Germany|France|Italy|Austria)\s*:/;

function isStandaloneContinuationUrlOrNote(plain: string): boolean {
  return /^(?:https?:\/\/|www\.|doi\s*:|10\.\d{4,9}\/|retrieved\b|accessed\b|available\s+(?:at|from)\b|archived\s+at\b|\[online\])/i.test(
    plain.trim()
  );
}

function looksLikeClearNewReference(html: string, plain: string): boolean {
  const t = plain.trim();
  if (!t) return false;

  // Numbered or 3-em-dash repeated-author entry
  if (/^(?:\[\d+\]|\d+\.\s+[A-Z“"'])/.test(t)) return true;
  if (/^(?:[—–_]{2,}|-{3,})[.,\s]/.test(t)) return true;

  // APA author + parenthesized year near start
  if (/^[^“"<>]{2,300}?\((?:\d{4}[a-z]?(?:[–/-]\d{2,4})?(?:,\s*[A-Za-z0-9 .–/-]+)?|n\.d\.|in press|forthcoming|ca\.\s*\d{4})\)\.?\s+\S/i.test(t)) {
    return true;
  }

  // Chicago Author-Date ("Smith, Jane. 2020. ...")
  if (/^[A-ZÀ-ÖØ-Þ][^“"<>]{1,180}?\.\s+(?:1[5-9]\d{2}|20\d{2})[a-z]?\.\s+\S/.test(t)) {
    return true;
  }

  // Surname, GivenName / Initials (excluding "Cambridge, MA: Publisher")
  if (!CITY_STATE_PUBLISHER_RE.test(t) && /^[A-ZÀ-ÖØ-Þ][A-Za-zÀ-ÿ'’ -]{0,45},\s+(?:[A-ZÀ-ÖØ-Þ][A-Za-zÀ-ÿ.'’ -]+)/.test(t)) {
    return true;
  }

  // Lowercase surname particles ("de la Motte, Diether", "van Beethoven, Ludwig", "von Glahn, Denise")
  if (/^(?:van|von|de|del|della|di|du|da|la|le|d'|d’)\s*[A-ZÀ-ÖØ-Þ][A-Za-zÀ-ÿ'’ -]+,\s+[A-ZÀ-ÖØ-Þ]/.test(t)) {
    return true;
  }

  // Organization or title-first entry with quoted or italicized title
  if (/^[“"'][^”"']{3,}[”"']/.test(t)) return true;
  if (/^<em>[^<]{3,}<\/em>\s*(?:\.|,|s\.v\.|\()/i.test(html.trim())) return true;

  return false;
}

function isPreviousCitationIncomplete(currentCitationHtml: string): boolean {
  const plain = htmlToPlain(currentCitationHtml).trim();
  if (!plain) return false;

  // Ends with mid-sentence punctuation or connector word
  if (/[,;:(\[/–-]\s*$/.test(plain)) return true;
  if (/\b(?:and|or|in|of|for|to|from|with|by|at|on|the|a|an|vol\.|no\.|pp\.|p\.|ed\.|eds\.|trans\.|comp\.|rev\.|doi)\s*$/i.test(plain)) {
    return true;
  }

  // Bare author or author+year stub with no title yet
  if (plain.length < 42 && /^[A-ZÀ-ÖØ-Þ][^.?!"“]+(?:\(\d{4}[a-z]?\))?\.$/.test(plain)) {
    return true;
  }

  // Ends with terminal punctuation, URL/DOI, or closing bracket/number -> complete!
  if (/[.?!][”"’')\]]*$/.test(plain)) return false;
  if (/(?:https?:\/\/\S+|10\.\d{4,9}\/\S+|doi:\s*\S+)$/i.test(plain)) return false;
  if (/\d\)?$/.test(plain)) return false;

  return true;
}

/**
 * Splits run-on citations if two separate references were pasted onto the exact same line
 * right after a DOI/URL (e.g., "... https://doi.org/10.1080/12345 Adams, J. (2020). ...").
 */
function splitRunOnDoiCitations(lineHtml: string): string[] {
  const results: string[] = [];
  let remaining = lineHtml.trim();

  const runOnRe =
    /((?:<a\b[^>]*>[\s\S]*?<\/a>|https?:\/\/(?:dx\.)?doi\.org\/[^\s<>"']+|doi:\s*10\.\d{4,9}\/[^\s<>"']+)\.?)\s+(?=[A-ZÀ-ÖØ-Þ][A-Za-zÀ-ÿ'’ -]{1,35},\s+(?:[A-Z]\.|[A-Z][a-z]+)[\s\S]{15,})/i;

  while (remaining) {
    const match = runOnRe.exec(remaining);
    if (!match || match.index === undefined) {
      results.push(remaining);
      break;
    }

    const cutIndex = match.index + match[1].length;
    const candidateNext = remaining.slice(cutIndex).trim();
    const candidatePlain = htmlToPlain(candidateNext);

    if (looksLikeClearNewReference(candidateNext, candidatePlain)) {
      results.push(remaining.slice(0, cutIndex).trim());
      remaining = candidateNext;
    } else {
      results.push(remaining);
      break;
    }
  }

  return results.filter(Boolean);
}

export function segmentReferenceEntries(rawLines: RawReferenceLine[]): string[] {
  const expanded: RawReferenceLine[] = [];
  for (const item of rawLines) {
    const pieces = splitRunOnDoiCitations(item.html);
    pieces.forEach((piece, idx) => {
      expanded.push({
        ...item,
        html: piece,
        afterBlankLine: idx === 0 ? item.afterBlankLine : true,
      });
    });
  }

  const citations: string[] = [];
  let currentParts: string[] = [];
  let firstMeta: RawReferenceLine | null = null;

  for (const line of expanded) {
    const cleaned = cleanInline(line.html);
    if (!cleaned) continue;

    if (currentParts.length === 0 || !firstMeta) {
      currentParts = [cleaned];
      firstMeta = line;
      continue;
    }

    const currPlain = htmlToPlain(cleaned);
    const currentJoined = normalizeHtmlSpacing(currentParts.join(" "));
    let merge = false;

    if (line.afterBlankLine || line.hasNumbering) {
      merge = false;
    } else if (isStandaloneContinuationUrlOrNote(currPlain)) {
      merge = true;
    } else if (looksLikeClearNewReference(cleaned, currPlain)) {
      merge = false;
    } else if (isPreviousCitationIncomplete(currentJoined)) {
      merge = true;
    } else if (
      line.startsWithTab ||
      (line.hangingIndent === 0 && firstMeta.hangingIndent === 0 && line.leftIndent > firstMeta.leftIndent + 120) ||
      /^(?:pp?\.|vol\.|no\.|\(\d|\(pp\.|ed\.|trans\.|[a-z])/.test(currPlain)
    ) {
      const isLowercaseSurnameParticle = /^(?:van|von|de|del|della|di|du|da|la|le|d'|d’|al-|ibn|bin|bell\s+hooks)\b/.test(currPlain);
      merge = !isLowercaseSurnameParticle;
    }

    if (merge) {
      currentParts.push(cleaned);
    } else {
      citations.push(currentJoined);
      currentParts = [cleaned];
      firstMeta = line;
    }
  }

  if (currentParts.length > 0) {
    citations.push(normalizeHtmlSpacing(currentParts.join(" ")));
  }

  return citations;
}

