function appendParagraphToReferenceLines(
  p: Element,
  sawBlankBefore: boolean,
  rawReferenceLines: RawReferenceLine[],
  getParagraphDefaults: (p: Element) => { bold: boolean; italic: boolean },
  renderInline: (
    element: Element,
    footnoteMode?: boolean,
    inherited?: { bold: boolean; italic: boolean },
    suppressFormatting?: boolean
  ) => string,
  getNumbering: (p: Element) => [string, string] | null,
  getParagraphIndentInfo: (p: Element) => { leftIndent: number; hangingIndent: number; startsWithTab: boolean }
): void {
  const pDefaults = getParagraphDefaults(p);
  const renderedP = mergeAdjacentInlineTags(renderInline(p, false, pDefaults), true);
  const hasNumbering = Boolean(getNumbering(p));
  const { leftIndent, hangingIndent, startsWithTab } = getParagraphIndentInfo(p);

  // Split on soft line breaks (<w:br/> / Shift+Enter) so multi-line reference blocks don't merge into one <li>
  const subParts = renderedP.split(/<br\s*\/?>/gi);
  let blankBeforeSub = sawBlankBefore;

  subParts.forEach((sub, idx) => {
    const cleanedSub = cleanInline(sub);
    if (!cleanedSub) {
      blankBeforeSub = true;
      return;
    }
    rawReferenceLines.push({
      html: cleanedSub,
      hasNumbering: idx === 0 ? hasNumbering : false,
      leftIndent: idx === 0 ? leftIndent : 0,
      hangingIndent: idx === 0 ? hangingIndent : 0,
      startsWithTab: idx === 0 ? startsWithTab : /^(?:\s|&nbsp;){2,}/.test(sub),
      afterBlankLine: blankBeforeSub,
      isSoftBreak: idx > 0,
    });
    blankBeforeSub = false;
  });
}

async function parseDocxStructure(file: File | Blob) {
  const zip = await JSZip.loadAsync(file);
  const docFile = zip.file("word/document.xml");
  if (!docFile) {
    throw new Error("Invalid .docx file: word/document.xml not found");
  }

  const parser = new DOMParser();

  // 1. Read relationships
  const relationships: Record<string, string> = {};
  const relsFile = zip.file("word/_rels/document.xml.rels");
  if (relsFile) {
    const relsXml = await relsFile.async("text");
    const relsDoc = parser.parseFromString(relsXml, "application/xml");
    const relNodes = relsDoc.getElementsByTagNameNS(REL_NS, "Relationship");
    for (let i = 0; i < relNodes.length; i++) {
      const rel = relNodes[i];
      const id = rel.getAttribute("Id") || rel.getAttributeNS(REL_NS, "Id");
      const target = rel.getAttribute("Target");
      if (id && target) relationships[id] = target;
    }
  }

  // 2. Read footnote relationships
  const footnoteRels: Record<string, string> = {};
  const fnRelsFile = zip.file("word/_rels/footnotes.xml.rels");
  if (fnRelsFile) {
    const fnRelsXml = await fnRelsFile.async("text");
    const fnRelsDoc = parser.parseFromString(fnRelsXml, "application/xml");
    const relNodes = fnRelsDoc.getElementsByTagNameNS(REL_NS, "Relationship");
    for (let i = 0; i < relNodes.length; i++) {
      const rel = relNodes[i];
      const id = rel.getAttribute("Id") || rel.getAttributeNS(REL_NS, "Id");
      const target = rel.getAttribute("Target");
      if (id && target) footnoteRels[id] = target;
    }
  }

  // 3. Read styles (including bold/italic inheritance for character & paragraph styles)
  interface StyleDef {
    name: string;
    basedOn?: string;
    bold?: boolean;
    italic?: boolean;
  }
  const styles: Record<string, string> = {};
  const styleDefs: Record<string, StyleDef> = {};
  const stylesFile = zip.file("word/styles.xml");
  if (stylesFile) {
    const stylesXml = await stylesFile.async("text");
    const stylesDoc = parser.parseFromString(stylesXml, "application/xml");
    const styleNodes = stylesDoc.getElementsByTagNameNS(W_NS, "style");
    for (let i = 0; i < styleNodes.length; i++) {
      const s = styleNodes[i];
      const sId = s.getAttributeNS(W_NS, "styleId") || s.getAttribute("w:styleId");
      if (!sId) continue;

      const nameNodes = s.getElementsByTagNameNS(W_NS, "name");
      const nameVal =
        nameNodes.length > 0 ? nameNodes[0].getAttributeNS(W_NS, "val") || nameNodes[0].getAttribute("w:val") || "" : "";
      styles[sId] = nameVal;

      const basedOnNodes = s.getElementsByTagNameNS(W_NS, "basedOn");
      const basedOn =
        basedOnNodes.length > 0
          ? basedOnNodes[0].getAttributeNS(W_NS, "val") || basedOnNodes[0].getAttribute("w:val") || undefined
          : undefined;

      // Direct child rPr on the <w:style> element
      let styleRPr: Element | null = null;
      for (let j = 0; j < s.childNodes.length; j++) {
        const ch = s.childNodes[j] as Element;
        if (ch.nodeType === Node.ELEMENT_NODE && (ch.localName || ch.nodeName.split(":").pop()) === "rPr") {
          styleRPr = ch;
          break;
        }
      }

      styleDefs[sId] = {
        name: nameVal,
        basedOn,
        bold: propExplicit(styleRPr, "b"),
        italic: propExplicit(styleRPr, "i"),
      };
    }
  }

  const resolveStyleFormatting = (
    styleId: string | null | undefined,
    fallback: { bold: boolean; italic: boolean } = { bold: false, italic: false }
  ): { bold: boolean; italic: boolean } => {
    if (!styleId) return { ...fallback };
    const chain: StyleDef[] = [];
    const visited = new Set<string>();
    let curr: string | undefined = styleId;
    while (curr && !visited.has(curr) && styleDefs[curr]) {
      visited.add(curr);
      chain.unshift(styleDefs[curr]);
      curr = styleDefs[curr].basedOn;
    }

    let bold = fallback.bold;
    let italic = fallback.italic;
    for (const def of chain) {
      if (def.bold !== undefined) bold = def.bold;
      if (def.italic !== undefined) italic = def.italic;
      const lowerName = def.name.toLowerCase();
      if (def.italic === undefined && (lowerName === "emphasis" || lowerName === "italic" || lowerName === "book title")) {
        italic = true;
      }
      if (def.bold === undefined && lowerName === "strong") {
        bold = true;
      }
    }
    return { bold, italic };
  };

  const getParagraphDefaults = (p: Element): { bold: boolean; italic: boolean } => {
    const pPr = p.getElementsByTagNameNS(W_NS, "pPr")[0];
    const pStyle = pPr?.getElementsByTagNameNS(W_NS, "pStyle")[0];
    const styleId = pStyle ? pStyle.getAttributeNS(W_NS, "val") || pStyle.getAttribute("w:val") || "" : "";
    return resolveStyleFormatting(styleId, { bold: false, italic: false });
  };

  // 4. Read numbering
  const numbering: Record<string, NumberingLevel> = {};
  const numberingFile = zip.file("word/numbering.xml");
  if (numberingFile) {
    const numXml = await numberingFile.async("text");
    const numDoc = parser.parseFromString(numXml, "application/xml");
    const abstractLevels: Record<string, NumberingLevel> = {};

    const abstracts = numDoc.getElementsByTagNameNS(W_NS, "abstractNum");
    for (let i = 0; i < abstracts.length; i++) {
      const a = abstracts[i];
      const aId = a.getAttributeNS(W_NS, "abstractNumId") || a.getAttribute("w:abstractNumId") || "";
      const lvls = a.getElementsByTagNameNS(W_NS, "lvl");
      for (let j = 0; j < lvls.length; j++) {
        const lvl = lvls[j];
        const lvlId = lvl.getAttributeNS(W_NS, "ilvl") || lvl.getAttribute("w:ilvl") || "0";
        const fmtNodes = lvl.getElementsByTagNameNS(W_NS, "numFmt");
        const startNodes = lvl.getElementsByTagNameNS(W_NS, "start");
        const fmt = fmtNodes.length > 0 ? (fmtNodes[0].getAttributeNS(W_NS, "val") || fmtNodes[0].getAttribute("w:val") || "decimal") : "decimal";
        const start = startNodes.length > 0 ? (startNodes[0].getAttributeNS(W_NS, "val") || startNodes[0].getAttribute("w:val") || "1") : "1";
        abstractLevels[`${aId}:${lvlId}`] = { fmt, start };
      }
    }

    const nums = numDoc.getElementsByTagNameNS(W_NS, "num");
    for (let i = 0; i < nums.length; i++) {
      const n = nums[i];
      const numId = n.getAttributeNS(W_NS, "numId") || n.getAttribute("w:numId") || "";
      const absNodes = n.getElementsByTagNameNS(W_NS, "abstractNumId");
      const absId = absNodes.length > 0 ? (absNodes[0].getAttributeNS(W_NS, "val") || absNodes[0].getAttribute("w:val") || "") : "";
      for (const [key, level] of Object.entries(abstractLevels)) {
        const [currAbs, lvlId] = key.split(":");
        if (currAbs === absId) {
          numbering[`${numId}:${lvlId}`] = level;
        }
      }
    }
  }

  // 5. Read footnotes
  const footnotes: Record<string, Footnote> = {};
  const fnFile = zip.file("word/footnotes.xml");

  const renderInlineContext = {
    usedFootnotes: [] as string[],
    footnoteNumbers: {} as Record<string, number>
  };

  const renderRun = (
    run: Element,
    defaults: { bold: boolean; italic: boolean },
    footnoteMode: boolean,
    suppressFormatting: boolean
  ): string => {
    const rPrNodes = run.getElementsByTagNameNS(W_NS, "rPr");
    const rPr = rPrNodes.length > 0 ? rPrNodes[0] : null;
    const rStyleNode = rPr?.getElementsByTagNameNS(W_NS, "rStyle")[0];
    const rStyleId = rStyleNode ? rStyleNode.getAttributeNS(W_NS, "val") || rStyleNode.getAttribute("w:val") || "" : "";
    const styleDefaults = rStyleId ? resolveStyleFormatting(rStyleId, defaults) : defaults;

    const bold = propEnabled(rPr, "b", styleDefaults.bold);
    const italic = propEnabled(rPr, "i", styleDefaults.italic);
    const vertical = vertAlign(rPr);
    const parts: string[] = [];
    let hasFootnoteRef = false;
    let hasNonFootnoteContent = false;

    for (let i = 0; i < run.childNodes.length; i++) {
      const child = run.childNodes[i] as Element;
      if (child.nodeType !== Node.ELEMENT_NODE) continue;
      const localName = child.localName || child.nodeName.split(":").pop();

      if (localName === "rPr") continue;
      if (localName === "t") {
        parts.push(htmlText(child.textContent || ""));
        if (child.textContent) hasNonFootnoteContent = true;
      } else if (localName === "tab") {
        parts.push(" ");
        hasNonFootnoteContent = true;
      } else if (localName === "br" || localName === "cr") {
        parts.push("<br>");
        hasNonFootnoteContent = true;
      } else if (localName === "noBreakHyphen") {
        parts.push("&#8209;");
        hasNonFootnoteContent = true;
      } else if (localName === "softHyphen") {
        parts.push("&shy;");
        hasNonFootnoteContent = true;
      } else if (localName === "footnoteReference") {
        hasFootnoteRef = true;
        if (!footnoteMode) {
          const sId = child.getAttributeNS(W_NS, "id") || child.getAttribute("w:id") || "";
          if (sId) {
            if (!(sId in renderInlineContext.footnoteNumbers)) {
              renderInlineContext.footnoteNumbers[sId] = renderInlineContext.usedFootnotes.length + 1;
              renderInlineContext.usedFootnotes.push(sId);
            }
            const num = renderInlineContext.footnoteNumbers[sId];
            const fn = footnotes[sId];
            let tooltipHtml = fn ? fn.paragraphs.join(" ").trim() : "";
            tooltipHtml = tooltipHtml.replace(/<a\s+href="https?:\/\/[^"]*">\s*<\/a>/gi, "");
            tooltipHtml = tooltipHtml.replace(/<a\s+href="https?:\/\/[^"]*">([^<]*)<\/a>/gi, "$1");
            const tip = tooltipHtml ? ` ${tooltipHtml}` : "";
            parts.push(
              `<a href="#_ftn${num}" id="_ftnref${num}">` +
              `<span class="tooltip-cms"><sup>[${num}]</sup>` +
              `<span class="tooltiptext-cms">${tip}</span></span></a>`
            );
          }
        }
      }
    }

    let rendered = parts.join("");
    if (!rendered) return "";

    const hasMeaningfulText = Boolean(rendered.replace(/(?:\s|&nbsp;)+/g, ""));
    if (suppressFormatting) return rendered;
    if (hasFootnoteRef && !hasNonFootnoteContent) return rendered;

    if (vertical === "superscript") rendered = `<sup>${rendered}</sup>`;
    else if (vertical === "subscript") rendered = `<sub>${rendered}</sub>`;

    if (!hasMeaningfulText) return rendered;

    if (italic) rendered = `<em>${rendered}</em>`;
    if (bold) rendered = `<strong>${rendered}</strong>`;

    return rendered;
  };

  const extractHyperlinkFromInstr = (instr: string): string | null => {
    const match = instr.match(/HYPERLINK\s+(?:\\[a-z]\s+(?:"[^"]*"\s+)?)*"([^"]+)"/i);
    return match ? match[1].trim() : null;
  };

  const renderInline = (
    element: Element,
    footnoteMode: boolean = false,
    inherited?: { bold: boolean; italic: boolean },
    suppressFormatting: boolean = false,
    rels: Record<string, string> = relationships
  ): string => {
    const defaults = inherited || { bold: false, italic: false };
    const parts: string[] = [];
    let activeField: { stage: "instr" | "display"; instr: string; displayParts: string[] } | null = null;

    const flushField = () => {
      if (!activeField) return;
      const inner = activeField.displayParts.join("");
      const href = extractHyperlinkFromInstr(activeField.instr);
      if (cleanInline(inner)) {
        parts.push(href ? `<a href="${htmlAttr(href)}">${inner}</a>` : inner);
      }
      activeField = null;
    };

    for (let i = 0; i < element.childNodes.length; i++) {
      const child = element.childNodes[i] as Element;
      if (child.nodeType !== Node.ELEMENT_NODE) continue;
      const localName = child.localName || child.nodeName.split(":").pop();

      if (localName === "r") {
        const fldChars = child.getElementsByTagNameNS(W_NS, "fldChar");
        if (fldChars.length > 0) {
          const fldType = fldChars[0].getAttributeNS(W_NS, "fldCharType") || fldChars[0].getAttribute("w:fldCharType");
          if (fldType === "begin") {
            flushField();
            activeField = { stage: "instr", instr: "", displayParts: [] };
            continue;
          } else if (fldType === "separate" && activeField) {
            activeField.stage = "display";
            continue;
          } else if (fldType === "end" && activeField) {
            flushField();
            continue;
          }
        }

        if (activeField && activeField.stage === "instr") {
          const instrNodes = child.getElementsByTagNameNS(W_NS, "instrText");
          for (let j = 0; j < instrNodes.length; j++) {
            activeField.instr += instrNodes[j].textContent || "";
          }
          continue;
        }

        const renderedRun = renderRun(child, defaults, footnoteMode, suppressFormatting);
        if (activeField && activeField.stage === "display") {
          activeField.displayParts.push(renderedRun);
        } else {
          parts.push(renderedRun);
        }
      } else if (localName === "fldSimple") {
        const instr = child.getAttributeNS(W_NS, "instr") || child.getAttribute("w:instr") || "";
        const href = extractHyperlinkFromInstr(instr);
        const inner = renderInline(child, footnoteMode, defaults, suppressFormatting, rels);
        if (cleanInline(inner)) {
          const out = href ? `<a href="${htmlAttr(href)}">${inner}</a>` : inner;
          if (activeField && activeField.stage === "display") activeField.displayParts.push(out);
          else parts.push(out);
        }
      } else if (localName === "hyperlink") {
        const inner = renderInline(child, footnoteMode, defaults, suppressFormatting, rels);
        const relId = child.getAttributeNS(R_NS, "id") || child.getAttribute("r:id") || child.getAttribute("id");
        const anchor = child.getAttributeNS(W_NS, "anchor") || child.getAttribute("w:anchor");
        let href = relId ? (rels[relId] || "") : "";
        if (!href && anchor) href = `#${anchor}`;
        if (cleanInline(inner)) {
          const out = href ? `<a href="${htmlAttr(href)}">${inner}</a>` : inner;
          if (activeField && activeField.stage === "display") activeField.displayParts.push(out);
          else parts.push(out);
        }
      } else if (["proofErr", "bookmarkStart", "bookmarkEnd"].includes(localName || "")) {
        continue;
      } else {
        const nested = renderInline(child, footnoteMode, defaults, suppressFormatting, rels);
        if (activeField && activeField.stage === "display") activeField.displayParts.push(nested);
        else parts.push(nested);
      }
    }

    flushField();
    return mergeAdjacentInlineTags(parts.join(""), false);
  };

  if (fnFile) {
    const fnXml = await fnFile.async("text");
    const fnDoc = parser.parseFromString(fnXml, "application/xml");
    const fnNodes = fnDoc.getElementsByTagNameNS(W_NS, "footnote");
    for (let i = 0; i < fnNodes.length; i++) {
      const fnNode = fnNodes[i];
      const sId = fnNode.getAttributeNS(W_NS, "id") || fnNode.getAttribute("w:id");
      if (!sId) continue;

      const pNodes = fnNode.getElementsByTagNameNS(W_NS, "p");
      const paragraphs: string[] = [];
      for (let j = 0; j < pNodes.length; j++) {
        let r = renderInline(pNodes[j], true, getParagraphDefaults(pNodes[j]), false, footnoteRels);
        r = cleanInline(r);
        if (r) paragraphs.push(r);
      }
      footnotes[sId] = { sourceId: sId, paragraphs };
    }
  }

  // 6. Process Main Document
  const docXml = await docFile.async("text");
  const doc = parser.parseFromString(docXml, "application/xml");
  const bodyNodes = doc.getElementsByTagNameNS(W_NS, "body");
  const paragraphs: Element[] = [];
  if (bodyNodes.length > 0) {
    const body = bodyNodes[0];
    for (let i = 0; i < body.childNodes.length; i++) {
      const child = body.childNodes[i] as Element;
      if (child.nodeType === Node.ELEMENT_NODE && (child.localName || child.nodeName.split(":").pop()) === "p") {
        paragraphs.push(child);
      }
    }
  }

  const getNumbering = (p: Element): [string, string] | null => {
    const pPr = p.getElementsByTagNameNS(W_NS, "pPr")[0];
    if (!pPr) return null;
    const numPr = pPr.getElementsByTagNameNS(W_NS, "numPr")[0];
    if (!numPr) return null;
    const numIdNode = numPr.getElementsByTagNameNS(W_NS, "numId")[0];
    const ilvlNode = numPr.getElementsByTagNameNS(W_NS, "ilvl")[0];
    if (!numIdNode) return null;
    const numId = numIdNode.getAttributeNS(W_NS, "val") || numIdNode.getAttribute("w:val") || "0";
    const ilvl = ilvlNode ? (ilvlNode.getAttributeNS(W_NS, "val") || ilvlNode.getAttribute("w:val") || "0") : "0";
    return [numId, ilvl];
  };

  const getParagraphIndentInfo = (p: Element): { leftIndent: number; hangingIndent: number; startsWithTab: boolean } => {
    const pPr = p.getElementsByTagNameNS(W_NS, "pPr")[0];
    const ind = pPr?.getElementsByTagNameNS(W_NS, "ind")[0];
    const readTwips = (attr: string): number => {
      if (!ind) return 0;
      const raw = ind.getAttributeNS(W_NS, attr) || ind.getAttribute(`w:${attr}`) || "0";
      const parsed = parseInt(raw, 10);
      return Number.isFinite(parsed) ? parsed : 0;
    };
    const leftIndent = readTwips("left") || readTwips("start");
    const hangingIndent = readTwips("hanging");
    const rawDirect = directText(p);
    const startsWithTab = /^\t/.test(rawDirect);
    return { leftIndent, hangingIndent, startsWithTab };
  };

  return {
    styles,
    numbering,
    footnotes,
    renderInlineContext,
    paragraphs,
    getParagraphDefaults,
    renderInline,
    getNumbering,
    getParagraphIndentInfo,
  };
}

export async function extractReferencesFromDocx(
  file: File | Blob,
  options: ExtractReferencesOptions = {}
): Promise<ExtractedDocxReferences> {
  const { includeHeading = false } = options;
  const {
    paragraphs,
    getParagraphDefaults,
    renderInline,
    getNumbering,
    getParagraphIndentInfo,
  } = await parseDocxStructure(file);

  if (paragraphs.length === 0) {
    return { html: "", citations: [], formattedCitations: [], count: 0, foundHeading: false };
  }

  let headingIdx = -1;
  for (let i = 0; i < paragraphs.length; i++) {
    const text = paragraphText(paragraphs[i]);
    if (text && isReferenceHeading(text)) {
      headingIdx = i;
      break;
    }
  }

  const foundHeading = headingIdx !== -1;
  const targetParagraphs = foundHeading ? paragraphs.slice(headingIdx + 1) : paragraphs;
  const rawReferenceLines: RawReferenceLine[] = [];
  let sawBlankInReferences = false;

  for (const p of targetParagraphs) {
    const text = paragraphText(p);
    if (!text) {
      sawBlankInReferences = true;
      continue;
    }
    if (isReferenceHeading(text)) {
      sawBlankInReferences = true;
      continue;
    }

    appendParagraphToReferenceLines(
      p,
      sawBlankInReferences,
      rawReferenceLines,
      getParagraphDefaults,
      renderInline,
      getNumbering,
      getParagraphIndentInfo
    );
    sawBlankInReferences = false;
  }

  const citations = segmentReferenceEntries(rawReferenceLines);
  if (citations.length === 0) {
    return { html: "", citations: [], formattedCitations: [], count: 0, foundHeading };
  }

  const formattedCitations = citations.map((c) => formatReferenceCitation(c));
  const outLines: string[] = [];
  if (includeHeading) {
    outLines.push('<h2 class="h4">References</h2>');
  }
  outLines.push('<ol class="references">');
  for (const formatted of formattedCitations) {
    outLines.push(`<li class="hangingindent">${formatted}</li>`);
  }
  outLines.push("</ol>");

  return {
    html: outLines.join("\n"),
    citations,
    formattedCitations,
    count: formattedCitations.length,
    foundHeading,
  };
}

export async function convertDocxToArticleHtml(file: File | Blob, options: ConvertArticleOptions = {}): Promise<string> {
  const {
    skipLeading = 0,
    includeReferences = true,
    includeFootnotes = true,
    h3Headings = new Set<string>()
  } = options;

  const {
    styles,
    numbering,
    footnotes,
    renderInlineContext,
    paragraphs,
    getParagraphDefaults,
    renderInline,
    getNumbering,
    getParagraphIndentInfo,
  } = await parseDocxStructure(file);

  if (paragraphs.length === 0) return "";

  const getHeadingLevel = (p: Element): number | null => {
    const text = paragraphText(p);
    if (text.length > 120) return null;

    const pPr = p.getElementsByTagNameNS(W_NS, "pPr")[0];
    const pStyle = pPr?.getElementsByTagNameNS(W_NS, "pStyle")[0];
    const styleId = pStyle ? (pStyle.getAttributeNS(W_NS, "val") || pStyle.getAttribute("w:val") || "") : "";
    const styleName = styles[styleId] || "";
    const styleKey = `${styleId} ${styleName}`.toLowerCase().replace(/\s+/g, "");

    if (styleKey.includes("heading1")) return 2;
    if (styleKey.includes("heading2")) return 3;

    // Check numbering
    const numPr = pPr?.getElementsByTagNameNS(W_NS, "numPr")[0];
    if (numPr) return null;

    // Check if all runs are bold
    const rNodes = p.getElementsByTagNameNS(W_NS, "r");
    const meaningfulRuns: Element[] = [];
    for (let i = 0; i < rNodes.length; i++) {
      if (directText(rNodes[i]).trim()) meaningfulRuns.push(rNodes[i]);
    }

    if (meaningfulRuns.length > 0) {
      const allBold = meaningfulRuns.every(r => {
        const rPrNode = r.getElementsByTagNameNS(W_NS, "rPr")[0];
        return propEnabled(rPrNode, "b", false);
      });
      if (allBold) {
        const anyItalic = meaningfulRuns.some(r => {
          const rPrNode = r.getElementsByTagNameNS(W_NS, "rPr")[0];
          return propEnabled(rPrNode, "i", false);
        });
        return anyItalic ? 3 : 2;
      }
    }

    return null;
  };

  const lines: string[] = [];
  const rawReferenceLines: RawReferenceLine[] = [];
  let skipped = 0;
  let openList: { tag: string; attrs: string } | null = null;
  let inReferences = false;
  let sawBlankInReferences = false;

  const closeList = () => {
    if (openList) {
      lines.push(`</${openList.tag}>`);
      openList = null;
    }
  };

  const htmlListType = (fmt: string): string => {
    return {
      decimal: "1",
      lowerLetter: "a",
      upperLetter: "A",
      lowerRoman: "i",
      upperRoman: "I",
    }[fmt] || "1";
  };

  for (const p of paragraphs) {
    const text = paragraphText(p);
    if (!text) {
      if (inReferences) sawBlankInReferences = true;
      continue;
    }

    if (skipped < skipLeading) {
      skipped++;
      continue;
    }

    if (inReferences) {
      if (isReferenceHeading(text)) {
        sawBlankInReferences = true;
        continue;
      }
      appendParagraphToReferenceLines(
        p,
        sawBlankInReferences,
        rawReferenceLines,
        getParagraphDefaults,
        renderInline,
        getNumbering,
        getParagraphIndentInfo
      );
      sawBlankInReferences = false;
      continue;
    }

    if (isReferenceHeading(text)) {
      if (includeReferences) {
        inReferences = true;
        closeList();
        continue;
      }
      break;
    }

    const numInfo = getNumbering(p);
    if (numInfo) {
      const [numId, level] = numInfo;
      const numLevel = numbering[`${numId}:${level}`] || { fmt: "decimal", start: "1" };
      const listTag = numLevel.fmt === "bullet" ? "ul" : "ol";
      const listAttrs = listTag === "ol" ? ` start="${htmlAttr(numLevel.start)}" type="${htmlListType(numLevel.fmt)}"` : "";

      if (!openList || openList.tag !== listTag || openList.attrs !== listAttrs) {
        closeList();
        lines.push(`<${listTag}${listAttrs}>`);
        openList = { tag: listTag, attrs: listAttrs };
      }

      lines.push(`<li>${cleanInline(renderInline(p, false, getParagraphDefaults(p)))}</li>`);
      continue;
    }

    closeList();
    let level = getHeadingLevel(p);
    if (h3Headings.has(text)) {
      level = 3;
    }

    const rendered = cleanInline(renderInline(p, false, getParagraphDefaults(p), level === 2 || level === 3));
    if (level === 2) {
      lines.push(`<h2 class="h4">${rendered}</h2>`);
    } else if (level === 3) {
      lines.push(`<h3 class="h5">${rendered}</h3>`);
    } else {
      lines.push(`<p>${rendered}</p>`);
    }
  }

  closeList();

  // Footnotes
  if (includeFootnotes && renderInlineContext.usedFootnotes.length > 0) {
    lines.push("<p>&nbsp;</p>");
    for (const sourceId of renderInlineContext.usedFootnotes) {
      const number = renderInlineContext.footnoteNumbers[sourceId];
      const fn = footnotes[sourceId] || { sourceId, paragraphs: [""] };
      const bodyText = (fn.paragraphs || [""]).filter(Boolean).join(" ").trim();
      lines.push(
        `<p><a href="#_ftnref${number}" id="_ftn${number}"><sup>[${number}]</sup></a> ${bodyText}</p>`
      );
    }
  }

  // References
  if (includeReferences && rawReferenceLines.length > 0) {
    const citations = segmentReferenceEntries(rawReferenceLines);

    lines.push('<h2 class="h4">References</h2>', '<ol class="references">');
    for (const citation of citations) {
      lines.push(
        `<li class="hangingindent">${formatReferenceCitation(citation)}</li>`
      );
    }
    lines.push("</ol>");
  }

  return lines.join("\n") + "\n";
}
